import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(new URL("./package.json", import.meta.url));
const { default: openapiTS, astToString } = require("openapi-typescript");
const swagger2openapi = require("swagger2openapi");
const { parseDocument } = require("yaml");
const output = new URL(
	"../../shared/data/src/transport/generated/",
	import.meta.url,
);
const config = JSON.parse(
	await readFile(new URL("./schema.json", import.meta.url), "utf8"),
);
const args = new Set(process.argv.slice(2));
for (const arg of args) {
	if (arg !== "--check" && arg !== "--download") {
		throw new Error(`Unknown option: ${arg}`);
	}
}
if (args.has("--check") && args.has("--download")) {
	throw new Error(
		"--check reads committed artifacts; use --download separately.",
	);
}

for (const [name, expected] of Object.entries(config.generators)) {
	const actual = require(`${name}/package.json`).version;
	if (actual !== expected) {
		throw new Error(`${name}: expected ${expected}, installed ${actual}`);
	}
}

const sourcePath = new URL("rest-api.yaml", output);
let source;
try {
	source = args.has("--download") ? undefined : await readFile(sourcePath);
} catch (error) {
	if (error.code !== "ENOENT" || args.has("--check")) throw error;
}
if (!source) {
	const response = await fetch(config.url);
	if (!response.ok)
		throw new Error(`Schema download failed: HTTP ${response.status}`);
	source = Buffer.from(await response.arrayBuffer());
}
const digest = createHash("sha256").update(source).digest("hex");
if (digest !== config.sha256) {
	throw new Error(
		`Schema digest mismatch: expected ${config.sha256}, received ${digest}`,
	);
}

const document = parseDocument(source.toString("utf8"));
if (document.errors.length) throw document.errors[0];
const original = document.toJS({ maxAliasCount: 100 });
const converted = await swagger2openapi.convertObj(original, { patch: false });
const nodes = await openapiTS(converted.openapi, config.typeOptions);
// REUSE-IgnoreStart
const header = [
	"// SPDX-FileCopyrightText: 2026 Contributors to Incus <https://github.com/lxc/incus>",
	"// SPDX-License-Identifier: Apache-2.0",
	"// Generated by scripts/api/generate.mjs; do not edit.",
	"",
].join("\n");
// REUSE-IgnoreEnd
const generated = header + astToString(nodes);
const provenance = {
	source: config,
	conversion: { from: "Swagger 2.0", to: "OpenAPI 3.0.0", patch: false },
	models: "components.schemas",
	operations: "paths and operations",
	limitations: [
		"Types describe the pinned upstream document; they do not validate runtime responses.",
		"The upstream document contains query-bearing path keys, which are not valid OpenAPI paths.",
		"Several upstream models omit required properties; the generated properties remain optional.",
		"File endpoints omit response content and misdescribe raw request bodies and mode headers.",
		"The operation recursion=1 response is documented as an array but the server returns a status-keyed map.",
		"WebSocket upgrade descriptions do not define the complete messaging protocols.",
		"ETag and If-Match headers are incompletely described upstream.",
	],
	upstreamReferences: [
		`https://github.com/lxc/incus/blob/${config.commit}/doc/rest-api.yaml`,
		`https://github.com/lxc/incus/blob/${config.commit}/cmd/incusd/instance_file.go`,
		`https://github.com/lxc/incus/blob/${config.commit}/cmd/incusd/operations.go`,
	],
};
const artifacts = new Map([
	["rest-api.yaml", source],
	["schema.ts", Buffer.from(generated)],
	["provenance.json", Buffer.from(`${JSON.stringify(provenance, null, 2)}\n`)],
]);

if (!args.has("--check")) await mkdir(output, { recursive: true });
for (const [name, expected] of artifacts) {
	const destination = new URL(name, output);
	if (args.has("--check")) {
		const actual = await readFile(destination);
		if (!actual.equals(expected)) {
			throw new Error(
				`${name} is out of date; run npm run generate:incus-types.`,
			);
		}
	} else {
		await writeFile(destination, expected);
	}
}
console.log(
	`${args.has("--check") ? "Verified" : "Generated"} Incus API contracts in ${fileURLToPath(output)}`,
);
